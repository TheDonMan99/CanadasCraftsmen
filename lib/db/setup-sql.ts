// Builds one SQL script that does what `npm run db:setup` does, for pasting into the
// Supabase SQL Editor when this machine can't open a Postgres connection.
// It runs the real migrate() and seedDatabase() against a recorder, so it can't drift
// from them, and it's safe to re-run: done migrations and existing rows are skipped.

import type { CatalogOption, Settings } from '@/lib/config/catalog';
import type { Db } from './client';
import { migrate, MIGRATIONS_DIR } from './migrate';
import { seedDatabase } from './seed';

function literal(v: unknown): string {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean' || typeof v === 'number') return String(v);
  if (Array.isArray(v)) return v.length ? `array[${v.map(literal).join(', ')}]` : "'{}'";
  return `'${String(v).replace(/'/g, "''")}'`;
}

/** A tag for dollar-quoting `text` that doesn't occur inside it. */
function dollarTag(text: string, base: string): string {
  let tag = `$${base}$`;
  for (let i = 0; text.includes(tag); i++) tag = `$${base}${i}$`;
  return tag;
}

export async function buildSetupSql(catalog: CatalogOption[], settings: Settings, dir = MIGRATIONS_DIR): Promise<string> {
  const out: string[] = [];
  let migration: string | null = null;
  const recorder: Db = {
    query: async (text, params = []) => {
      if (/^select name from schema_migrations/.test(text)) return [];
      if (/^insert into schema_migrations/.test(text)) {
        // wrap the migration so it only runs once
        const name = literal(params[0]);
        const body = migration!;
        const q = dollarTag(body, 'migration');
        out.push(
          `do $setup$ begin\n  if not exists (select 1 from schema_migrations where name = ${name}) then\n    execute ${q}\n${body}\n${q};\n    insert into schema_migrations (name) values (${name});\n  end if;\nend $setup$;`,
        );
        migration = null;
        return [];
      }
      if (!params.length && migration === null && !/^create table if not exists schema_migrations/.test(text)) {
        migration = text;
        return [];
      }
      out.push(text.replace(/\s*\n\s*/g, ' ').replace(/\$(\d+)/g, (_, n) => literal(params[Number(n) - 1])) + ';');
      // pretend every insert added a row, so the font and inventory rows are written too;
      // their own "on conflict do nothing" keeps re-runs safe
      return (/returning/.test(text) ? [{}] : []) as any[];
    },
    tx: (fn) => fn(recorder),
  };
  await migrate(recorder, dir);
  await seedDatabase(recorder, catalog, settings);
  return [
    '-- Welcome sign app: database setup. Generated by `npm run db:sql`; do not edit by hand.',
    '-- Paste into Supabase → SQL Editor → Run. Safe to run again: it never overwrites your edits.',
    'begin;',
    ...out,
    'commit;',
    '',
  ].join('\n\n');
}
